export function t(key, lang, params = {}) {
  const s = STRINGS[lang]?.[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, p) => (p in params ? String(params[p]) : m));
}

/** English only for English browsers; everyone else gets Portuguese (the shelf-label language). */
export function detectLang(navigatorLanguage) {
  return /^en\b/i.test(navigatorLanguage ?? '') ? 'en' : 'pt';
}

export function formatPct(pct, lang) {
  return new Intl.NumberFormat(LOCALES[lang], { maximumFractionDigits: 1 }).format(pct);
}

/** Grams as kg with three decimals, the way scale labels print weight. */
export function formatKg(grams, lang) {
  const kg = new Intl.NumberFormat(LOCALES[lang], { minimumFractionDigits: 3, maximumFractionDigits: 3 }).format(grams / 1000);
  return `${kg} kg`;
}

/** A magnification with one decimal, the way camera apps show it: 2,5×. */
export function formatZoom(zoom, lang) {
  const x = new Intl.NumberFormat(LOCALES[lang], { minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(zoom);
  return `${x}×`;
}

/** An exposure bias in EV, signed and with one decimal, the way camera apps show it: +0,7 or −1,0. */
export function formatExposure(ev, lang) {
  const rounded = Math.round(ev * 10) / 10;
  const x = new Intl.NumberFormat(LOCALES[lang], { minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(Math.abs(rounded));
  return `${rounded > 0 ? '+' : rounded < 0 ? '−' : ''}${x}`;
}

/** A size the way Android's storage screen shows it, in thousands: 340 kB, 1,2 MB, 1,5 GB. */
export function formatBytes(bytes, lang) {
  const kB = Math.round(bytes / 1e3);
  // The unit is chosen after rounding, so 999,6 kB reads 1 MB rather than 1.000 kB.
  const [value, unit] = kB < 1000 ? [kB, 'kilobyte'] : bytes < 999.95e6 ? [bytes / 1e6, 'megabyte'] : [bytes / 1e9, 'gigabyte'];
  return new Intl.NumberFormat(LOCALES[lang], { style: 'unit', unit, maximumFractionDigits: 1 }).format(value);
}
